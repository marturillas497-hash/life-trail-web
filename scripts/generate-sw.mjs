/*
Runs after `next build`. Lists every file in the static export and writes
out/sw.js, a service worker that stores all of them so the app opens and works
with no internet. Each build gets its own cache name, so updates replace the
old files cleanly.
*/
import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

const OUT_DIR = "out";
const SKIP = new Set(["sw.js", "404.html"]);

async function walk(dir) {
  const entries = await readdir(dir, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(full)));
    else files.push(full);
  }
  return files;
}

function toUrl(relative) {
  const url = "/" + relative.split(path.sep).join("/");
  if (url === "/index.html") return "/";
  if (url.endsWith("/index.html")) return url.slice(0, -"index.html".length);
  return url;
}

const files = (await walk(OUT_DIR))
  .map((file) => path.relative(OUT_DIR, file))
  .filter((relative) => !SKIP.has(relative) && !relative.endsWith(".map") && !relative.startsWith("404" + path.sep))
  .sort();

const hash = createHash("sha1");
const urls = [];
for (const relative of files) {
  hash.update(relative);
  hash.update(await readFile(path.join(OUT_DIR, relative)));
  urls.push(toUrl(relative));
}
const version = hash.digest("hex").slice(0, 12);

const source = `/* Generated by scripts/generate-sw.mjs. Do not edit. */
const VERSION = ${JSON.stringify(version)};
const CACHE = "life-trail-" + VERSION;
const PRECACHE = ${JSON.stringify(urls, null, 2)};
const FALLBACK = "/journal/";

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      await cache.addAll(PRECACHE.map((url) => new Request(url, { cache: "reload" })));
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      const names = await caches.keys();
      await Promise.all(
        names.filter((name) => name.startsWith("life-trail-") && name !== CACHE).map((name) => caches.delete(name)),
      );
      await self.clients.claim();
    })(),
  );
});

self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  event.respondWith(respond(request, url));
});

async function respond(request, url) {
  const cache = await caches.open(CACHE);

  const cached = await cache.match(request, { ignoreSearch: true });
  if (cached) return cached;

  if (request.mode === "navigate" && !url.pathname.endsWith("/")) {
    const withSlash = await cache.match(url.pathname + "/");
    if (withSlash) return withSlash;
  }

  try {
    return await fetch(request);
  } catch (error) {
    if (request.mode === "navigate") {
      const fallback = await cache.match(FALLBACK);
      if (fallback) return fallback;
    }
    throw error;
  }
}
`;

await writeFile(path.join(OUT_DIR, "sw.js"), source);
console.log(`sw.js written: ${urls.length} files cached, version ${version}`);
